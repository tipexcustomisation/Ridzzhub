create extension if not exists pgcrypto;

create table public.products (
  id uuid primary key default gen_random_uuid(),
  brand text not null check (brand in ('ridzzprints','tipex')),
  name text not null,
  slug text not null unique,
  description text not null default '',
  price_pence integer not null check (price_pence >= 0),
  image_url text,
  category text not null default 'General',
  is_custom boolean not null default false,
  is_active boolean not null default true,
  stock_quantity integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  order_number bigint generated by default as identity unique,
  status text not null default 'pending' check (status in ('pending','confirmed','in_production','ready','shipped','completed','cancelled')),
  total_pence integer not null default 0 check (total_pence >= 0),
  currency text not null default 'GBP',
  customer_name text not null,
  contact_email text not null,
  delivery_address jsonb,
  notes text,
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','pending','paid','refunded')),
  payment_provider_reference text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price_pence integer not null check (unit_price_pence >= 0),
  customisation jsonb,
  created_at timestamptz not null default now()
);

create table public.custom_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  brand text not null check (brand in ('ridzzprints','tipex')),
  request_type text not null,
  title text not null,
  description text not null,
  reference_image_urls text[] not null default '{}',
  budget_pence integer check (budget_pence is null or budget_pence >= 0),
  status text not null default 'new' check (status in ('new','reviewing','quoted','accepted','in_progress','completed','declined')),
  admin_reply text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index products_brand_active_idx on public.products(brand, is_active);
create index orders_user_created_idx on public.orders(user_id, created_at desc);
create index order_items_order_idx on public.order_items(order_id);
create index custom_requests_user_created_idx on public.custom_requests(user_id, created_at desc);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.custom_requests enable row level security;

grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant select, insert, update on public.orders to authenticated;
grant select, insert on public.order_items to authenticated;
grant select, insert, update on public.custom_requests to authenticated;

create policy "Public can view active products"
on public.products for select to anon, authenticated
using (is_active = true or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admins manage products"
on public.products for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Customers view their own orders"
on public.orders for select to authenticated
using ((select auth.uid()) = user_id or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Customers create their own orders"
on public.orders for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "Customers update their own pending orders"
on public.orders for update to authenticated
using ((select auth.uid()) = user_id and status = 'pending')
with check ((select auth.uid()) = user_id and status = 'pending');

create policy "Customers view items for their orders"
on public.order_items for select to authenticated
using (exists (select 1 from public.orders o where o.id = order_id and (o.user_id = (select auth.uid()) or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')));

create policy "Customers add items to their own pending orders"
on public.order_items for insert to authenticated
with check (exists (select 1 from public.orders o where o.id = order_id and o.user_id = (select auth.uid()) and o.status = 'pending'));

create policy "Customers view their own custom requests"
on public.custom_requests for select to authenticated
using ((select auth.uid()) = user_id or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Customers create their own custom requests"
on public.custom_requests for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "Admins update custom requests"
on public.custom_requests for update to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');